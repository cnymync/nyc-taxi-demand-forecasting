def aggregate_to_zone_hour(df: DataFrame) -> DataFrame:
    """Group narrowed trip-level data to (taxi_type, pu_location_id, pickup_hour).

    `pickup_count` is the core target. The remaining narrowed columns don't
    survive to zone-hour grain as-is (they're per-trip), so they're
    collapsed into the summary stats that keep them meaningful at this
    grain rather than being dropped outright: mean distance/duration/
    passenger count, and a count of how many trips in that zone-hour were
    flagged extreme.
    """
    hourly = df.withColumn("pickup_hour", F.date_trunc("hour", F.col("pickup_datetime")))
    return hourly.groupBy("taxi_type", "pu_location_id", "pickup_hour").agg(
        F.count(F.lit(1)).alias("pickup_count"),
        F.avg("trip_distance").alias("avg_trip_distance"),
        F.avg("trip_duration_minutes").alias("avg_trip_duration_minutes"),
        F.avg("passenger_count").alias("avg_passenger_count"),
        F.sum(F.col("is_extreme_trip_distance").cast("int")).alias("extreme_trip_distance_count"),
        F.sum(F.col("is_extreme_trip_duration").cast("int")).alias("extreme_trip_duration_count"),
    )


