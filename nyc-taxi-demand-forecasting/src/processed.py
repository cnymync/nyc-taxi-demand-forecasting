"""Clean -> Processed pipeline: zone-hour pickup demand aggregation.

Reads Clean taxi data (`data/clean/taxi/`), narrows it to the columns
relevant to the demand-location research question, aggregates
to (taxi_type, pu_location_id, pickup_hour) pickup counts, and constructs
explicit zero-demand rows for every (taxi_type, zone, hour) combination in
the study period that had no pickups -- a zone-hour with no observed trips
is a real "zero demand" data point for this research question, not missing
data, and the model needs to see it to learn what "no demand" looks like.

Zero-demand rows are built over the 263 real geographic taxi zones (the
TLC lookup's 265 LocationIDs minus the two non-geographic placeholders,
264 "Unknown" and 265 "Outside of NYC" -- `UNKNOWN_NA_ZONE_IDS` in
`src/clean_rules.py`) and every hour in the study period
(`STUDY_PERIOD_START` .. `STUDY_PERIOD_END_EXCLUSIVE`). This is a flagged
assumption, not a directive found elsewhere: a "zero demand" data point
only makes sense for an actual physical service area.

Historical baseline (Phase 6 step 3, locked 2026-08-16; **revised 2026-08-17
("Round 3")**): a trailing 8-week rolling mean of
`pickup_count` at each (taxi_type, zone, day-of-week, hour-of-day) slot,
computed causally per row -- using only the up-to-8 occurrences of that
exact slot strictly *before* the row's own week, never the row's own week
or any later one. Applied uniformly to every row (train and test) via the
same window computation; leakage-safe by construction regardless of
whether the prior weeks used happen to fall in the training or test
period, since a row's baseline never depends on its own or a future
observation. This deliberately differs from a "compute once at the end of
2025 and freeze" design: it mirrors how a real fleet operator would
actually have last week's observed numbers on hand before this week, and
it is the direct trigger for what makes it track a within-period demand
trend rather than flattening it into one static number. A simple
hierarchical fallback (rolling zone+dow+hour -> rolling zone+hour ->
static borough+dow+hour -> static taxi-type-wide global, the latter two
still computed once from 2024-2025 training data only) covers slots with
too little rolling history to trust -- in practice, only the very first
calendar day of the whole study period (2024-01-01) actually needs it,
since the zone+hour rolling grain already has a full window within about
a week for every zone. **Originally deferred at Phase 6** ("only revisit
if EDA/evaluation shows the static baseline is inadequate") -- revisited
after Phase 11's evaluation found exactly that: actual demand in
low-volume zones (median baseline < 10) grew roughly 3-4x relative to the
flat 2024-2025 average by 2026, almost entirely a Yellow-taxi pattern, and
no model could represent a trend the static baseline had already averaged
away. The prior static implementation is preserved, not deleted, as
`compute_static_baseline_levels`/`add_static_historical_baseline`, for
reference and comparison.

External-source join (weather/events/holidays, locked 2026-08-16):
weather joins on `pickup_hour` alone (single LGA
station, so every zone in a given hour gets the same citywide reading --
weather data ends 2026-05-30 23:00, one day short of the study period's
2026-05-31, so the last day's rows get NULL weather, a real coverage gap,
not a bug); events are expanded from their `[start_date_time,
end_date_time]` span into the hourly `(pu_location_id, pickup_hour)` cells
they cover, then joined on `(pu_location_id, pickup_hour)` to produce
`event_present`/`event_count` (no finer event detail -- deliberately kept
to just these two per user instruction); holidays are joined on calendar
date (`holiday_schedule_clean.csv`, generated by
`standardise_holiday_schedule()` from the source `holiday_schedule.csv`,
whose `Date` column is reformatted from `M/D/YY` to the same
`YYYY-MM-DD HH:MM:SS` style used everywhere else, at midnight, since a
holiday indicator applies to the whole day).

Usage:
    python -m src.processed            # yellow + green, union, write Processed
    python -m src.processed yellow     # yellow only (no union/write)
    python -m src.processed green      # green only (no union/write)
"""

