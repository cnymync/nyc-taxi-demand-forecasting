def add_baseline_grain_columns(df: DataFrame) -> DataFrame:
    """day_of_week (Spark's `dayofweek`: 1=Sunday..7=Saturday) and
    hour_of_day (0-23) -- the grain the baseline is averaged over."""
    return df.withColumn("day_of_week", F.dayofweek("pickup_hour")).withColumn(
        "hour_of_day", F.hour("pickup_hour")
    )


def load_zone_boroughs(
    spark: SparkSession, lookup_path: Path = TAXI_ZONE_LOOKUP_PATH
) -> DataFrame:
    """`pu_location_id` -> `borough`, used only for the coarser fallback grain."""
    lookup = pd.read_csv(lookup_path)[["LocationID", "Borough"]].rename(
        columns={"LocationID": "pu_location_id", "Borough": "borough"}
    )
    return spark.createDataFrame(lookup)


def compute_static_baseline_levels(
    train_df: DataFrame, zone_boroughs: DataFrame
) -> dict[str, DataFrame]:
    """Original (Round 1/2) static baseline: mean training-period `pickup_count`
    at each grain in the fallback chain, from most to least specific. Every
    grain is a plain average over 2024-2025 zone-hour rows (including the
    explicit zero-demand ones -- those zero weeks are real signal, not gaps
    to skip). Preserved for reference/comparison; `add_static_historical_baseline`
    (below) is the only remaining caller -- the production pipeline now uses
    the rolling baseline instead (see module docstring, "Round 3")."""
    level_zone_dow_hour = train_df.groupBy(
        "taxi_type", "pu_location_id", "day_of_week", "hour_of_day"
    ).agg(
        F.avg("pickup_count").alias("baseline_zone_dow_hour"),
        F.sum((F.col("pickup_count") > 0).cast("int")).alias("n_nonzero_weeks"),
    )
    level_zone_hour = train_df.groupBy("taxi_type", "pu_location_id", "hour_of_day").agg(
        F.avg("pickup_count").alias("baseline_zone_hour")
    )
    train_with_borough = train_df.join(zone_boroughs, on="pu_location_id", how="left")
    level_borough_dow_hour = train_with_borough.groupBy(
        "taxi_type", "borough", "day_of_week", "hour_of_day"
    ).agg(F.avg("pickup_count").alias("baseline_borough_dow_hour"))
    level_global = train_df.groupBy("taxi_type").agg(
        F.avg("pickup_count").alias("baseline_global")
    )

    return {
        "zone_dow_hour": level_zone_dow_hour,
        "zone_hour": level_zone_hour,
        "borough_dow_hour": level_borough_dow_hour,
        "global": level_global,
    }


def add_static_historical_baseline(
    df: DataFrame,
    zone_boroughs: DataFrame,
    train_period_end_exclusive: str = TRAIN_PERIOD_END_EXCLUSIVE,
    min_obs: int = MIN_BASELINE_OBSERVATIONS,
) -> DataFrame:
    """Original (Round 1/2) static-baseline pipeline step, preserved verbatim
    for reference/comparison -- see `add_historical_baseline` for the rolling
    baseline now used in production.

    Joins a leakage-safe historical baseline onto every row (train and test).
    The baseline is computed only from rows before `train_period_end_exclusive`
    (2024-2025), then joined onto the *full* dataset including 2026 -- 2026
    rows receive a baseline value without ever contributing to it. Falls back
    through zone+dow+hour -> zone+hour -> borough+dow+hour -> taxi-type-wide
    global when the most specific grain has too few non-zero training weeks
    (`min_obs`) to trust.
    """
    df = add_baseline_grain_columns(df)
    train_df = df.where(F.col("pickup_hour") < F.lit(train_period_end_exclusive))
    levels = compute_static_baseline_levels(train_df, zone_boroughs)

    df = (
        df.join(zone_boroughs, on="pu_location_id", how="left")
        .join(
            levels["zone_dow_hour"],
            on=["taxi_type", "pu_location_id", "day_of_week", "hour_of_day"],
            how="left",
        )
        .join(levels["zone_hour"], on=["taxi_type", "pu_location_id", "hour_of_day"], how="left")
        .join(
            levels["borough_dow_hour"],
            on=["taxi_type", "borough", "day_of_week", "hour_of_day"],
            how="left",
        )
        .join(levels["global"], on="taxi_type", how="left")
    )

    zone_dow_hour_reliable = F.col("n_nonzero_weeks").isNotNull() & (
        F.col("n_nonzero_weeks") >= min_obs
    )
    df = df.withColumn(
        "baseline_pickup_count",
        F.when(zone_dow_hour_reliable, F.col("baseline_zone_dow_hour"))
        .when(F.col("baseline_zone_hour").isNotNull(), F.col("baseline_zone_hour"))
        .when(F.col("baseline_borough_dow_hour").isNotNull(), F.col("baseline_borough_dow_hour"))
        .otherwise(F.col("baseline_global")),
    ).withColumn(
        "baseline_source",
        F.when(zone_dow_hour_reliable, F.lit("zone_dow_hour"))
        .when(F.col("baseline_zone_hour").isNotNull(), F.lit("zone_hour"))
        .when(F.col("baseline_borough_dow_hour").isNotNull(), F.lit("borough_dow_hour"))
        .otherwise(F.lit("global")),
    )

    return df.drop(
        "borough",
        "baseline_zone_dow_hour",
        "n_nonzero_weeks",
        "baseline_zone_hour",
        "baseline_borough_dow_hour",
        "baseline_global",
    )


def add_rolling_baseline_columns(
    df: DataFrame, window_weeks: int = ROLLING_BASELINE_WINDOW_WEEKS
) -> DataFrame:
    """Add the two rolling-window baseline candidates as row-wise columns,
    computed directly via window functions (no groupBy+join needed, unlike
    the static levels -- a window function can look "backwards" from each
    row without collapsing the frame).

    `zone_dow_hour`: partitioned by the exact (taxi_type, zone, dow, hour)
    slot, ordered by time, averaged over the trailing `window_weeks` rows.
    The zero-demand grid guarantees exactly one row per slot per calendar
    week, so `rowsBetween(-window_weeks, -1)` is exactly "the previous
    `window_weeks` occurrences of this slot", i.e. the previous
    `window_weeks` calendar weeks -- and never the row's own week, so this
    is causal/leakage-safe by construction. `n_prior_zone_dow_hour_weeks`
    counts how many rows actually fell in that trailing frame (fewer than
    `window_weeks` only near the very start of the whole study period).

    `zone_hour`: the coarser fallback grain -- same slot but pooled across
    all 7 weekdays, so the equivalent trailing time span is
    `window_weeks * 7` rows (one per day at that hour, not one per week).
    """
    w_zone_dow_hour = (
        Window.partitionBy("taxi_type", "pu_location_id", "day_of_week", "hour_of_day")
        .orderBy("pickup_hour")
        .rowsBetween(-window_weeks, -1)
    )
    w_zone_hour = (
        Window.partitionBy("taxi_type", "pu_location_id", "hour_of_day")
        .orderBy("pickup_hour")
        .rowsBetween(-window_weeks * 7, -1)
    )
    return (
        df.withColumn("baseline_zone_dow_hour", F.avg("pickup_count").over(w_zone_dow_hour))
        .withColumn("n_prior_zone_dow_hour_weeks", F.count("pickup_count").over(w_zone_dow_hour))
        .withColumn("baseline_zone_hour", F.avg("pickup_count").over(w_zone_hour))
    )


def add_historical_baseline(
    df: DataFrame,
    zone_boroughs: DataFrame,
    train_period_end_exclusive: str = TRAIN_PERIOD_END_EXCLUSIVE,
    window_weeks: int = ROLLING_BASELINE_WINDOW_WEEKS,
    min_obs: int = MIN_BASELINE_OBSERVATIONS,
) -> DataFrame:
    """Add a leakage-safe historical baseline onto every row (train and test) --
    Round 3 (2026-08-17): trailing `window_weeks`-week rolling mean, not a
    single static 2024-2025 average (see module docstring).

    Falls back through rolling zone+dow+hour -> rolling zone+hour -> static
    borough+dow+hour -> static taxi-type-wide global when the most specific
    rolling grain doesn't yet have a full trailing window
    (`n_prior_zone_dow_hour_weeks >= window_weeks`). The two coarse fallback
    levels are still the original static (train-only) computation --
    revisiting them to also be rolling was judged not worth the added
    complexity, since the static distribution showed they're essentially
    never reached (0 rows fell back that far in Round 1/2) once the two
    rolling grains are in play; they only matter for the very first
    calendar day of the study period here.
    """
    df = add_baseline_grain_columns(df)
    train_df = df.where(F.col("pickup_hour") < F.lit(train_period_end_exclusive))
    static_levels = compute_static_baseline_levels(train_df, zone_boroughs)

    df = (
        df.join(zone_boroughs, on="pu_location_id", how="left")
        .join(
            static_levels["borough_dow_hour"],
            on=["taxi_type", "borough", "day_of_week", "hour_of_day"],
            how="left",
        )
        .join(static_levels["global"], on="taxi_type", how="left")
    )
    df = add_rolling_baseline_columns(df, window_weeks=window_weeks)

    zone_dow_hour_reliable = F.col("n_prior_zone_dow_hour_weeks") >= window_weeks
    df = df.withColumn(
        "baseline_pickup_count",
        F.when(zone_dow_hour_reliable, F.col("baseline_zone_dow_hour"))
        .when(F.col("baseline_zone_hour").isNotNull(), F.col("baseline_zone_hour"))
        .when(F.col("baseline_borough_dow_hour").isNotNull(), F.col("baseline_borough_dow_hour"))
        .otherwise(F.col("baseline_global")),
    ).withColumn(
        "baseline_source",
        F.when(zone_dow_hour_reliable, F.lit("zone_dow_hour"))
        .when(F.col("baseline_zone_hour").isNotNull(), F.lit("zone_hour"))
        .when(F.col("baseline_borough_dow_hour").isNotNull(), F.lit("borough_dow_hour"))
        .otherwise(F.lit("global")),
    )

    return df.drop(
        "borough",
        "baseline_zone_dow_hour",
        "n_prior_zone_dow_hour_weeks",
        "baseline_zone_hour",
        "baseline_borough_dow_hour",
        "baseline_global",
    )


