def write_processed_zone_hour(df: DataFrame, output_dir: Path = PROCESSED_DATA_DIR) -> Path:
    """Write the combined (Yellow + Green) zone-hour pickup table as one file."""
    output_dir.mkdir(parents=True, exist_ok=True)
    target = output_dir / "pickups_zone_hour.parquet"
    df.coalesce(1).write.mode("overwrite").parquet(str(target) + "_tmp")

    tmp_dir = Path(str(target) + "_tmp")
    part_files = list(tmp_dir.glob("part-*.parquet"))
    if len(part_files) != 1:
        raise RuntimeError(f"Expected exactly one part file in {tmp_dir}, found {len(part_files)}")
    if target.exists():
        target.unlink()
    part_files[0].rename(target)
    for leftover in tmp_dir.glob("*"):
        leftover.unlink()
    tmp_dir.rmdir()

    logger.info(f"Wrote combined Processed zone-hour dataset to {target}")
    return target


def write_report(
    results: list[dict],
    report_dir: Path = PROCESSED_DATA_QUALITY_DIR,
    baseline_source_counts: dict | None = None,
    external_join_coverage: dict | None = None,
) -> None:
    """Write the per-taxi-type Processed summary (CSV + JSON), plus the
    baseline-source distribution and external-join coverage when given."""
    report_dir.mkdir(parents=True, exist_ok=True)
    run_ts = datetime.now(timezone.utc).isoformat()
    summary_rows = [
        {
            "taxi_type": r["taxi_type"],
            "clean_row_count": r["clean_row_count"],
            "non_zero_zone_hour_count": r["non_zero_zone_hour_count"],
            "grid_row_count": r["grid_row_count"],
            "result_row_count": r["result_row_count"],
            "pct_zero_demand": round(
                100
                * (r["result_row_count"] - r["non_zero_zone_hour_count"])
                / r["result_row_count"],
                4,
            ),
        }
        for r in results
    ]
    df = pd.DataFrame(summary_rows)
    df.to_csv(report_dir / "processed_summary.csv", index=False)
    with open(report_dir / "processed_summary.json", "w") as f:
        pd.Series(
            {
                "run_timestamp": run_ts,
                "summary": summary_rows,
                "baseline_source_distribution": baseline_source_counts,
                "external_join_coverage": external_join_coverage,
            }
        ).to_json(f, indent=2)
    logger.info(f"Processed data-quality report written to {report_dir}")


