def load_geographic_zone_ids(lookup_path: Path = TAXI_ZONE_LOOKUP_PATH) -> list[int]:
    """TLC LocationIDs with real geometry -- excludes the non-geographic
    placeholders 264 ("Unknown") and 265 ("Outside of NYC")."""
    lookup = pd.read_csv(lookup_path)
    return sorted(int(z) for z in lookup["LocationID"] if int(z) not in UNKNOWN_NA_ZONE_IDS)


def build_zone_hour_grid(
    spark: SparkSession,
    taxi_type: str,
    zone_ids: list[int],
    start: str = STUDY_PERIOD_START,
    end_exclusive: str = STUDY_PERIOD_END_EXCLUSIVE,
) -> DataFrame:
    """Every (taxi_type, zone, hour) combination in the study period -- the
    full grid that `pickup_count` gets left-joined onto so every zone-hour
    with no observed trips is still represented, explicitly, as zero.
    """
    hours_df = spark.sql(
        f"""
        SELECT explode(sequence(
            to_timestamp('{start}'),
            to_timestamp('{end_exclusive}') - INTERVAL 1 HOUR,
            INTERVAL 1 HOUR
        )) AS pickup_hour
        """
    )
    zones_df = spark.createDataFrame([(z,) for z in zone_ids], ["pu_location_id"])
    return (
        hours_df.withColumn("taxi_type", F.lit(taxi_type))
        .crossJoin(zones_df)
        .select("taxi_type", "pu_location_id", "pickup_hour")
    )


def add_zero_demand_rows(grid_df: DataFrame, agg_df: DataFrame) -> DataFrame:
    """Left-join the grid onto the aggregate; missing `pickup_count` becomes
    0 (a real zero-demand observation). The other summary stats are left
    NULL for zero-demand rows -- there is no "average distance" of zero
    trips, and that's meaningfully different from an average of exactly 0.
    """
    joined = grid_df.join(agg_df, on=["taxi_type", "pu_location_id", "pickup_hour"], how="left")
    return joined.withColumn(
        "pickup_count", F.coalesce(F.col("pickup_count"), F.lit(0))
    ).withColumn("is_zero_demand_hour", F.col("pickup_count") == 0)


