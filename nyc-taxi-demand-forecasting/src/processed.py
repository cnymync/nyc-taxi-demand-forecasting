def build_zone_hour_taxi_type(spark: SparkSession, taxi_type: str) -> dict:
    """Run the full Clean -> Processed zone-hour workflow for one taxi type."""
    clean_df = load_clean(spark, taxi_type)
    clean_row_count = clean_df.count()
    logger.info(f"[{taxi_type}] loaded {clean_row_count:,} Clean rows")

    narrowed = narrow_to_processed_columns(clean_df)
    agg_df = aggregate_to_zone_hour(narrowed)
    non_zero_row_count = agg_df.count()

    zone_ids = load_geographic_zone_ids()
    grid_df = build_zone_hour_grid(spark, taxi_type, zone_ids)
    grid_row_count = grid_df.count()

    result_df = add_zero_demand_rows(grid_df, agg_df)
    result_row_count = result_df.count()

    logger.success(
        f"[{taxi_type}] Processed zone-hour: {result_row_count:,} rows "
        f"({non_zero_row_count:,} with pickups, "
        f"{result_row_count - non_zero_row_count:,} explicit zero-demand)"
    )

    return {
        "taxi_type": taxi_type,
        "result_df": result_df,
        "clean_row_count": clean_row_count,
        "non_zero_zone_hour_count": non_zero_row_count,
        "grid_row_count": grid_row_count,
        "result_row_count": result_row_count,
    }


