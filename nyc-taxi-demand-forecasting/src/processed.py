def load_weather(spark: SparkSession, path: Path = WEATHER_CLEAN_PATH) -> DataFrame:
    """LGA hourly weather, one row per hour, already at the exact grain
    needed to join onto `pickup_hour` -- no zone dimension (citywide)."""
    return (
        spark.read.option("header", True)
        .option("inferSchema", True)
        .csv(str(path))
        .withColumn("pickup_hour", F.to_timestamp("date_hour"))
        .drop("date_hour")
    )


def join_weather(df: DataFrame, weather_df: DataFrame) -> DataFrame:
    """Left-join citywide weather onto every zone for that hour.

    Weather data ends 2026-05-30 23:00, one day short of the study period's
    2026-05-31 -- that last day's rows get NULL weather columns. A real
    coverage gap in the source data, not something to fabricate a fix for.
    """
    return df.join(weather_df, on="pickup_hour", how="left")


def load_events(spark: SparkSession, path: Path = EVENTS_CLEAN_PATH) -> DataFrame:
    """Cleaned events, restricted to those already geocoded to a taxi zone --
    events with no zone can't contribute to any zone's event count. Not all
    events geocode successfully; see the "geocoding" block written by
    `src/external_events.py::write_events_report` (or notebook `03`'s own
    printed output) for the exact current coverage rate."""
    df = (
        spark.read.option("header", True)
        .option("inferSchema", True)
        .csv(str(path))
        .where(F.col("pu_location_id").isNotNull())
    )
    return df.select(
        F.col("pu_location_id").cast("int").alias("pu_location_id"),
        F.to_timestamp("start_date_time").alias("start_date_time"),
        F.to_timestamp("end_date_time").alias("end_date_time"),
    )


def expand_events_to_zone_hour(events_df: DataFrame) -> DataFrame:
    """Expand each event's `[start_date_time, end_date_time]` span into the
    hourly `(pu_location_id, pickup_hour)` cells it covers, then collapse to
    `event_count` per cell -- an event running 00:00-23:00 the same day
    covers 24 hourly cells in the zone it's geocoded to, and a zone-hour
    with two overlapping events gets `event_count = 2`.
    """
    exploded = events_df.withColumn(
        "pickup_hour",
        F.explode(
            F.sequence(
                F.date_trunc("hour", F.col("start_date_time")),
                F.date_trunc("hour", F.col("end_date_time")),
                F.expr("INTERVAL 1 HOUR"),
            )
        ),
    )
    return exploded.groupBy("pu_location_id", "pickup_hour").agg(
        F.count(F.lit(1)).alias("event_count")
    )


def join_events(df: DataFrame, events_zone_hour_df: DataFrame) -> DataFrame:
    """Left-join per-zone-hour event counts; no match means no event (0/False),
    not missing data -- events are not taxi-type-specific, so this doesn't
    join on `taxi_type`."""
    joined = df.join(events_zone_hour_df, on=["pu_location_id", "pickup_hour"], how="left")
    return joined.withColumn("event_count", F.coalesce(F.col("event_count"), F.lit(0))).withColumn(
        "event_present", F.col("event_count") > 0
    )


def standardise_holiday_schedule(
    raw_path: Path = HOLIDAY_RAW_PATH, clean_path: Path = HOLIDAY_CLEAN_PATH
) -> pd.DataFrame:
    """Reformat the source `Date` column (`M/D/YY`, e.g. `1/1/24`) to the
    `YYYY-MM-DD HH:MM:SS` style used by every other external-data file
    (weather's `date_hour`, the taxi zone-hour grid), at midnight -- a
    holiday indicator applies to the whole day, not one specific hour.

    Two source rows can share the same calendar date -- e.g. 2025-01-20 is
    both "Birthday of Martin Luther King, Jr." and "Inauguration Day" (a
    real, once-every-4-years coincidence, not a data error). Collapsed to
    one row per date (names joined with "; ") so the later join onto the
    zone-hour table can't fan out a date's rows out to 2x.

    Writes the standardised file and also returns it (for tests).
    """
    raw = pd.read_csv(raw_path)
    raw["date"] = pd.to_datetime(raw["Date"], format="%m/%d/%y").dt.strftime("%Y-%m-%d 00:00:00")
    standardised = (
        raw.groupby("date")["Holiday"]
        .apply(lambda names: "; ".join(names))
        .reset_index()
        .rename(columns={"Holiday": "holiday_name"})
        .sort_values("date")
        .reset_index(drop=True)
    )
    clean_path.parent.mkdir(parents=True, exist_ok=True)
    standardised.to_csv(clean_path, index=False)
    logger.info(f"Wrote standardised holiday schedule to {clean_path}")
    return standardised


def load_holidays(spark: SparkSession, path: Path = HOLIDAY_CLEAN_PATH) -> DataFrame:
    """Load the standardised holiday schedule, one row per calendar date."""
    return (
        spark.read.option("header", True)
        .option("inferSchema", True)
        .csv(str(path))
        .withColumn("date", F.to_timestamp("date"))
    )


def join_holidays(df: DataFrame, holidays_df: DataFrame) -> DataFrame:
    """Left-join on calendar date (every hour of a holiday date matches)."""
    df = df.withColumn("pickup_date", F.date_trunc("day", F.col("pickup_hour")))
    holidays_df = holidays_df.withColumnRenamed("date", "pickup_date")
    joined = df.join(holidays_df, on="pickup_date", how="left")
    return joined.withColumn("is_holiday", F.col("holiday_name").isNotNull()).drop("pickup_date")


def join_external_sources(
    df: DataFrame,
    spark: SparkSession,
    weather_path: Path = WEATHER_CLEAN_PATH,
    events_path: Path = EVENTS_CLEAN_PATH,
    holiday_raw_path: Path = HOLIDAY_RAW_PATH,
    holiday_clean_path: Path = HOLIDAY_CLEAN_PATH,
) -> DataFrame:
    """Join weather, events, and holidays onto the zone-hour table (Phase 6 step 4)."""
    weather_df = load_weather(spark, weather_path)
    df = join_weather(df, weather_df)

    events_df = load_events(spark, events_path)
    events_zone_hour_df = expand_events_to_zone_hour(events_df)
    df = join_events(df, events_zone_hour_df)

    standardise_holiday_schedule(holiday_raw_path, holiday_clean_path)
    holidays_df = load_holidays(spark, holiday_clean_path)
    df = join_holidays(df, holidays_df)

    return df


