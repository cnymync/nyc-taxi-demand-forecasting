app = typer.Typer()


@app.command()
def main(
    taxi_type: str = typer.Argument(
        "all",
        help="Which dataset to process: 'yellow', 'green', or 'all' (unions and writes Processed).",
    ),
):
    """Run the Clean -> Processed zone-hour aggregation pipeline."""
    if taxi_type not in {"all", "yellow", "green"}:
        raise typer.BadParameter("taxi_type must be 'all', 'yellow', or 'green'")

    spark = (
        SparkSession.builder.appName("nyc-taxi-clean-to-processed")
        .master("local[*]")
        # Pin the session timezone -- without this, Spark's date_trunc/
        # sequence/to_timestamp calls silently use the *driver machine's*
        # OS timezone, not a property of the data. On a machine set to
        # Australia/Melbourne, that machine's October DST transition
        # corrupted the hourly grid (a spring-forward gap manifested as a
        # duplicated local timestamp string), which fanned out into
        # duplicate rows once holidays/events were joined on it -- found
        # 2026-08-16. UTC has no DST, so pickup
        # timestamps (already naive/no-tz strings from the TLC data) are
        # never reinterpreted through a foreign calendar.
        .config("spark.sql.session.timeZone", "UTC")
        .config("spark.driver.memory", "16g")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")

    if taxi_type == "all":
        results = [
            build_zone_hour_taxi_type(spark, "yellow"),
            build_zone_hour_taxi_type(spark, "green"),
        ]
        combined_df = results[0]["result_df"].unionByName(results[1]["result_df"])

        zone_boroughs = load_zone_boroughs(spark)
        combined_df = add_historical_baseline(combined_df, zone_boroughs)
        baseline_source_counts = {
            row["baseline_source"]: row["count"]
            for row in combined_df.groupBy("baseline_source").count().collect()
        }
        logger.info(f"Baseline source distribution: {baseline_source_counts}")

        combined_df = join_external_sources(combined_df, spark)
        total_rows = combined_df.count()
        coverage_row = combined_df.agg(
            F.sum(F.col("tmpf").isNotNull().cast("int")).alias("weather_matched"),
            F.sum(F.col("event_present").cast("int")).alias("event_present_rows"),
            F.sum(F.col("is_holiday").cast("int")).alias("holiday_rows"),
        ).collect()[0]
        external_join_coverage = {
            "total_rows": total_rows,
            "weather_matched_rows": coverage_row["weather_matched"],
            "pct_weather_matched": round(100 * coverage_row["weather_matched"] / total_rows, 4),
            "event_present_rows": coverage_row["event_present_rows"],
            "pct_event_present": round(100 * coverage_row["event_present_rows"] / total_rows, 4),
            "holiday_rows": coverage_row["holiday_rows"],
            "pct_holiday": round(100 * coverage_row["holiday_rows"] / total_rows, 4),
        }
        logger.info(f"External-source join coverage: {external_join_coverage}")

        write_processed_zone_hour(combined_df)
        write_report(
            results,
            baseline_source_counts=baseline_source_counts,
            external_join_coverage=external_join_coverage,
        )
        logger.success(
            "Combined Processed zone-hour dataset: "
            f"Yellow {results[0]['result_row_count']:,} + Green {results[1]['result_row_count']:,} rows"
        )
    else:
        result = build_zone_hour_taxi_type(spark, taxi_type)
        write_report([result])
        logger.info(
            f"Ran in single-taxi-type mode ('{taxi_type}'); Processed dataset not written (use 'all')."
        )

    spark.stop()


if __name__ == "__main__":
    app()
